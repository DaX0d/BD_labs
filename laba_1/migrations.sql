BEGIN;

CREATE TABLE flight_changes (
    change_id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_id                integer     NOT NULL,
    new_departure_airport_id integer     NOT NULL,
    new_arrival_airport_id   integer     NOT NULL,
    new_departure_time       timestamptz NOT NULL,
    new_arrival_time         timestamptz NOT NULL,
    changed_at               timestamptz NOT NULL DEFAULT now(),
    reason                   varchar(255),

    CONSTRAINT ck_flight_changes_airports_differ
        CHECK (new_departure_airport_id <> new_arrival_airport_id),
    CONSTRAINT ck_flight_changes_time_order
        CHECK (new_arrival_time > new_departure_time),
    CONSTRAINT uq_flight_changes_flight_changed_at
        UNIQUE (flight_id, changed_at),

    CONSTRAINT fk_flight_changes_flight FOREIGN KEY (flight_id)
        REFERENCES flights (flight_id) ON DELETE CASCADE,
    CONSTRAINT fk_flight_changes_departure_airport FOREIGN KEY (new_departure_airport_id)
        REFERENCES airports (airport_id) ON DELETE RESTRICT,
    CONSTRAINT fk_flight_changes_arrival_airport FOREIGN KEY (new_arrival_airport_id)
        REFERENCES airports (airport_id) ON DELETE RESTRICT
);

COMMIT;
