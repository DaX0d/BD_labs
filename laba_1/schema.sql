DROP TABLE IF EXISTS tickets     CASCADE;
DROP TABLE IF EXISTS flights     CASCADE;
DROP TABLE IF EXISTS airports    CASCADE;
DROP TABLE IF EXISTS user_emails CASCADE;
DROP TABLE IF EXISTS users       CASCADE;

CREATE TABLE users (
    user_id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    last_name       varchar(100) NOT NULL,
    first_name      varchar(100) NOT NULL,
    middle_name     varchar(100),
    birth_date      date         NOT NULL,
    passport_number varchar(20)  NOT NULL,
    created_at      timestamptz  NOT NULL DEFAULT now(),

    CONSTRAINT uq_users_passport UNIQUE (passport_number),
    CONSTRAINT ck_users_birth_date CHECK (birth_date <= CURRENT_DATE),
    CONSTRAINT ck_users_passport_format CHECK (passport_number ~ '^[0-9A-Z ]{6,20}$')
);

CREATE TABLE user_emails (
    email_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    integer      NOT NULL,
    email      varchar(255) NOT NULL,
    is_primary boolean      NOT NULL DEFAULT false,

    CONSTRAINT uq_user_emails_email UNIQUE (email),
    CONSTRAINT ck_user_emails_format CHECK (email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
    CONSTRAINT ck_user_emails_lower  CHECK (email = lower(email)),
    CONSTRAINT fk_user_emails_user FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX uq_user_emails_one_primary
    ON user_emails (user_id) WHERE is_primary;

CREATE INDEX idx_user_emails_user ON user_emails (user_id);

CREATE TABLE airports (
    airport_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iata_code  char(3)      NOT NULL,
    name       varchar(150) NOT NULL,
    city       varchar(100) NOT NULL,
    country    varchar(100) NOT NULL,

    CONSTRAINT uq_airports_iata UNIQUE (iata_code),
    CONSTRAINT ck_airports_iata_format CHECK (iata_code ~ '^[A-Z]{3}$')
);

CREATE TABLE flights (
    flight_id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_number        varchar(10)   NOT NULL,
    departure_airport_id integer       NOT NULL,
    arrival_airport_id   integer       NOT NULL,
    departure_time       timestamptz   NOT NULL,
    arrival_time         timestamptz   NOT NULL,
    base_price           numeric(10,2) NOT NULL,
    total_seats          smallint      NOT NULL,
    status               varchar(20)   NOT NULL DEFAULT 'scheduled',

    CONSTRAINT uq_flights_number_departure UNIQUE (flight_number, departure_time),
    CONSTRAINT ck_flights_airports_differ  CHECK (departure_airport_id <> arrival_airport_id),
    CONSTRAINT ck_flights_time_order       CHECK (arrival_time > departure_time),
    CONSTRAINT ck_flights_base_price       CHECK (base_price > 0),
    CONSTRAINT ck_flights_total_seats      CHECK (total_seats > 0),
    CONSTRAINT ck_flights_status           CHECK (status IN ('scheduled', 'delayed', 'departed', 'arrived', 'cancelled')),
    CONSTRAINT ck_flights_number_format    CHECK (flight_number ~ '^[A-Z0-9]{2}[0-9]{1,4}$'),
    CONSTRAINT fk_flights_departure_airport FOREIGN KEY (departure_airport_id)
        REFERENCES airports (airport_id) ON DELETE RESTRICT,
    CONSTRAINT fk_flights_arrival_airport FOREIGN KEY (arrival_airport_id)
        REFERENCES airports (airport_id) ON DELETE RESTRICT
);

CREATE INDEX idx_flights_route ON flights (departure_airport_id, arrival_airport_id, departure_time);
CREATE INDEX idx_flights_arrival_airport ON flights (arrival_airport_id);

CREATE TABLE tickets (
    ticket_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     integer       NOT NULL,
    flight_id   integer       NOT NULL,
    seat_number varchar(4)    NOT NULL,
    price       numeric(10,2) NOT NULL,
    status      varchar(20)   NOT NULL DEFAULT 'booked',
    booked_at   timestamptz   NOT NULL DEFAULT now(),

    CONSTRAINT uq_tickets_flight_seat UNIQUE (flight_id, seat_number),
    CONSTRAINT ck_tickets_price       CHECK (price >= 0),
    CONSTRAINT ck_tickets_status      CHECK (status IN ('booked', 'paid', 'cancelled')),
    CONSTRAINT ck_tickets_seat_format CHECK (seat_number ~ '^[0-9]{1,2}[A-F]$'),
    CONSTRAINT fk_tickets_user FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_tickets_flight FOREIGN KEY (flight_id)
        REFERENCES flights (flight_id) ON DELETE RESTRICT
);

CREATE INDEX idx_tickets_user ON tickets (user_id);
